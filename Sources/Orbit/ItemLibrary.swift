import AppKit
import Combine
import CryptoKit
import ImageIO
import UniformTypeIdentifiers
import OrbitCore

/// Serial pasteboard access keeps lazy providers and image decoding off the UI thread.
actor ItemLibraryIO {
    let folder: URL
    private var changeCount = -1
    private var revision = 0
    private var loadFailure: Error?
    init(folder: URL) { self.folder = folder }
    func load() throws -> [StoredItem] {
        let url = folder.appendingPathComponent("items.json")
        guard FileManager.default.fileExists(atPath: url.path) else { return [] }
        do {
            let data = try Data(contentsOf: url)
            guard data.count < 8_000_000 else { throw CocoaError(.fileReadTooLarge) }
            let items = try JSONDecoder().decode([StoredItem].self, from: data)
            loadFailure = nil
            return items.filter { $0.asset == nil || ($0.asset == URL(fileURLWithPath: $0.asset!).lastPathComponent && FileManager.default.fileExists(atPath: folder.appendingPathComponent($0.asset!).path)) }
        } catch { loadFailure = error; throw error }
    }
    func save(_ items: [StoredItem], persist: Bool, revision: Int) throws {
        // Never replace an unreadable library with an apparently empty history.
        if let loadFailure { throw loadFailure }
        guard revision >= self.revision else { return }; self.revision = revision
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        let url = folder.appendingPathComponent("items.json")
        try JSONEncoder().encode(persist ? items : []).write(to: url, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        let assets = Set(items.compactMap(\.asset))
        for url in (try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)) ?? [] where url.pathExtension == "png" && !assets.contains(url.lastPathComponent) { try? FileManager.default.removeItem(at: url) }
    }
    func fileItem(_ url: URL) -> StoredItem {
        var item = StoredItem(kind: .files, text: url.lastPathComponent, paths: [url.path])
        if let bookmark = try? url.bookmarkData(options: .minimalBookmark, includingResourceValuesForKeys: nil, relativeTo: nil) { item.bookmarks = [url.path: bookmark] }
        return item
    }
    func importImage(_ url: URL) throws -> StoredItem? { try image(Data(contentsOf: url)) }
    func image(_ data: Data) throws -> StoredItem? {
        guard data.count <= 25_000_000, let source = CGImageSourceCreateWithData(data as CFData, nil),
              let metadata = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = metadata[kCGImagePropertyPixelWidth] as? Int, let height = metadata[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, width <= 16000, height <= 16000, width * height <= 40_000_000,
              let image = NSBitmapImageRep(data: data),
              let png = image.representation(using: .png, properties: [:]), png.count <= 25_000_000 else { return nil }
        let name = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined() + ".png"
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try png.write(to: folder.appendingPathComponent(name), options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: folder.appendingPathComponent(name).path)
        return StoredItem(kind: .image, text: "Image · \(image.pixelsWide) × \(image.pixelsHigh)", asset: name)
    }
    func readClipboard(skip: Bool) -> StoredItem? {
        let pb = NSPasteboard.general, count = pb.changeCount
        guard count != changeCount else { return nil }; changeCount = count
        if skip { return nil }
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !excluded.contains(where: { pb.types?.contains(.init($0)) == true }) else { return nil }
        var item: StoredItem?
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let safeURLs = Array(urls.filter(\.isFileURL).prefix(100)), paths = safeURLs.map(\.path)
            var files = StoredItem(kind: .files, text: safeURLs.map(\.lastPathComponent).joined(separator: ", "), paths: paths)
            files.bookmarks = Dictionary(uniqueKeysWithValues: safeURLs.compactMap { url in (try? url.bookmarkData(options: .minimalBookmark, includingResourceValuesForKeys: nil, relativeTo: nil)).map { (url.path, $0) } })
            item = files
        } else if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) { item = try? image(data) }
        else if let value = pb.string(forType: .string), !value.isEmpty, value.utf8.count <= 1_000_000 {
            let link = URL(string: value.trimmingCharacters(in: .whitespacesAndNewlines)).map { ["https", "http"].contains($0.scheme?.lowercased() ?? "") } ?? false
            item = StoredItem(kind: link ? .link : .text, text: value)
        }
        // A provider may have changed the clipboard while fulfilling a lazy representation.
        guard pb.changeCount == count else { return nil }; return item
    }
    func copy(_ item: StoredItem) -> Bool {
        let pb = NSPasteboard.general
        if item.kind == .files {
            let urls = ItemFileReference.urls(item).filter { FileManager.default.fileExists(atPath: $0.path) }
            guard !urls.isEmpty else { return false }; pb.clearContents(); _ = pb.writeObjects(urls as [NSURL])
        } else if let asset = item.asset {
            guard let data = try? Data(contentsOf: folder.appendingPathComponent(asset)) else { return false }
            pb.clearContents(); pb.setData(data, forType: .png)
        } else { pb.clearContents(); pb.setString(item.text, forType: .string) }
        changeCount = pb.changeCount; return true
    }
}

@MainActor final class ItemLibrary: ObservableObject {
    @Published private(set) var items: [StoredItem] = []
    @Published var message: String?
    private let io: ItemLibraryIO
    let folder: URL
    private let shelf: Bool
    private var task: Task<Void, Never>?
    private var generation = 0
    private var revision = 0
    private var persistence = false
    private var enabled = false
    private var configured = false
    private var loading = false
    private var savePending = false
    private var limit = 100
    init(shelf: Bool) {
        self.shelf = shelf; folder = OrbitPaths.support.appendingPathComponent(shelf ? "Shelf" : "Clipboard", isDirectory: true)
        io = ItemLibraryIO(folder: folder)
        if shelf { persistence = true; enabled = true; loadSaved() }
    }
    func configure(enabled: Bool, persistence: Bool, limit: Int) {
        guard !shelf else { return }
        self.limit = limit
        let wasEnabled = self.enabled, wasPersistent = self.persistence
        if configured, wasEnabled == enabled, wasPersistent == persistence { return }
        configured = true
        generation += 1
        self.enabled = enabled; self.persistence = persistence
        task?.cancel(); task = nil
        loading = false
        if !enabled { items = []; save(); return }
        if persistence && (!wasPersistent || !wasEnabled) {
            loadSaved()
        } else if !persistence && wasPersistent { save() }
    }
    private func loadSaved() {
        loading = true
        let token = generation
        Task {
            do {
                let saved = try await io.load()
                guard token == generation, enabled else { return }
                // New drops made while disk access was pending stay at the front.
                items.append(contentsOf: saved.filter { savedItem in !items.contains { $0.signature == savedItem.signature } })
                trim()
            } catch {
                guard token == generation else { return }
                message = "Saved library could not be read. Its files have been preserved."
            }
            guard token == generation else { return }
            loading = false
            if savePending { savePending = false; save() }
        }
    }
    func poll(excludedApps: [String]) {
        guard enabled, !shelf, !loading, task == nil else { return }
        let skip = excludedApps.contains(NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "")
        let token = generation
        task = Task { [weak self] in
            guard let self else { return }
            let item = await io.readClipboard(skip: skip)
            guard token == generation else { return }; task = nil
            if enabled, let item { add(item) }
        }
    }
    func add(_ item: StoredItem) {
        var incoming = item
        if let existing = items.first(where: { $0.signature == item.signature }) { incoming.pinned = existing.pinned }
        items.removeAll { $0.signature == item.signature }; items.insert(incoming, at: 0); trim(); save()
    }
    private func trim() {
        var count = 0
        items = items.filter { item in if item.pinned { return true }; count += 1; return count <= limit }
        items = Array(items.prefix(200))
    }
    private func save() {
        guard !loading else { savePending = true; return }
        revision += 1; let value = revision, saved = items, persist = persistence
        Task { do { try await io.save(saved, persist: persist, revision: value) } catch { message = "Could not save: \(error.localizedDescription)" } }
    }

    func togglePin(_ id: UUID) { if let index = items.firstIndex(where: { $0.id == id }) { items[index].pinned.toggle(); save() } }
    func remove(_ id: UUID) { items.removeAll { $0.id == id }; save() }
    func clear() { items.removeAll { !$0.pinned }; save() }
    func copy(_ item: StoredItem) { Task { message = await io.copy(item) ? "Copied" : "The original file is no longer available" } }
    func assetURL(_ item: StoredItem) -> URL? { item.asset.map { folder.appendingPathComponent($0) } }
    func urls(_ item: StoredItem) -> [URL] {
        if let asset = assetURL(item) { return [asset] }
        if item.kind == .link, let url = URL(string: item.text), ["https", "http"].contains(url.scheme?.lowercased() ?? "") { return [url] }
        return ItemFileReference.urls(item)
    }
    func choose() {
        let panel = NSOpenPanel(); panel.canChooseDirectories = true; panel.allowsMultipleSelection = true
        if panel.runModal() == .OK { addURLs(panel.urls) }
    }
    func importItem(_ item: StoredItem, from source: ItemLibrary) {
        if let url = source.assetURL(item) { Task { do { if let owned = try await io.importImage(url) { add(owned) } } catch { message = error.localizedDescription } } }
        else { add(item) }
    }
    func shutdown() {
        generation += 1; task?.cancel(); task = nil
        if !shelf && !persistence { try? FileManager.default.removeItem(at: folder) }
    }
    func addURLs(_ urls: [URL]) {
        for url in urls.prefix(100) {
            if url.isFileURL { Task { let item = await io.fileItem(url); add(item) } }
            else if ["http", "https"].contains(url.scheme?.lowercased() ?? "") { add(StoredItem(kind: .link, text: url.absoluteString)) }
        }
    }
    func accept(_ providers: [NSItemProvider]) -> Bool {
        let supported = providers.filter { p in [UTType.fileURL, .url, .image, .plainText].contains { p.hasItemConformingToTypeIdentifier($0.identifier) } }
        guard !supported.isEmpty else { return false }
        Task {
            for provider in supported.prefix(100) {
                let type = [UTType.fileURL, .url, .png, .tiff, .image, .plainText].first { provider.hasItemConformingToTypeIdentifier($0.identifier) }!
                let data: Data? = await withCheckedContinuation { next in provider.loadDataRepresentation(forTypeIdentifier: type.identifier) { data, _ in next.resume(returning: data) } }
                guard let data else { continue }
                if type == .fileURL || type == .url, let url = URL(dataRepresentation: data, relativeTo: nil) { addURLs([url]) }
                else if type.conforms(to: .image), let item = try? await io.image(data) { add(item) }
                else if let text = String(data: data, encoding: .utf8), text.utf8.count <= 1_000_000 { add(StoredItem(kind: .text, text: text)) }
            }
        }
        return true
    }
}

private enum ItemFileReference {
    static func urls(_ item: StoredItem) -> [URL] {
        item.paths.map { path in
            var stale = false
            if let bookmark = item.bookmarks?[path], let url = try? URL(resolvingBookmarkData: bookmark, options: [.withoutUI, .withoutMounting], relativeTo: nil, bookmarkDataIsStale: &stale) { return url }
            return URL(fileURLWithPath: path)
        }
    }
}
